"""Render the quality-rule registry as documentation and export the GX Expectation Suites.

Outputs
  docs/quality_rules.md            human-readable table of every rule (requirement -> ... -> action)
  docs/gx_expectation_mapping.csv  one row per GX Expectation with its rule_id
  gx/expectation_suites/*.json     every Expectation Suite as JSON
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.quality_rules import ALL_RULES            # noqa: E402
from src.validation import export_suites           # noqa: E402


def _fmt_kwargs(kw: dict) -> str:
    out = []
    for k, v in kw.items():
        if k == "__dataset__":
            continue
        if callable(v):
            v = "<run-time value>"
        elif isinstance(v, (list, tuple)) and len(v) > 6:
            v = f"[{len(v)} values]"
        out.append(f"{k}={v}")
    return ", ".join(out)


def main() -> None:
    lines = ["# Data-quality rules\n",
             "_Generated by `scripts/export_quality_rules.py` from `src/quality_rules.py` - the same registry that builds the "
             "executed Great Expectations Suites. Do not edit by hand._\n",
             f"**{len(ALL_RULES)} rules** / **{sum(len(r.specs) for r in ALL_RULES)} Expectations**.\n",
             "Severity policy: `critical` -> STOP (task fails, downstream blocked, no retry); `warning` -> continue and "
             "record; `info` -> record only.\n"]
    for layer, title in (("raw", "Raw layer (before transformation)"), ("prepared", "Prepared layer (before load)")):
        lines.append(f"\n## {title}\n")
        lines.append("| ID | Dataset | Attribute | Dimension | Rule | Metric | Threshold | Severity | Req. | Pipeline action |")
        lines.append("|---|---|---|---|---|---|---|---|---|---|")
        for r in (x for x in ALL_RULES if x.layer == layer):
            lines.append(f"| {r.rule_id} | {r.dataset} | {r.attribute} | {r.dimension} | {r.statement} | {r.metric} | "
                         f"{r.threshold} | **{r.severity}** | {r.requirements} | {r.action} |")
        lines.append(f"\n### Justification and GX Expectations - {layer}\n")
        for r in (x for x in ALL_RULES if x.layer == layer):
            lines.append(f"**{r.rule_id}** - {r.justification}  ")
            for cls, kw in r.specs:
                lines.append(f"- `{cls}({_fmt_kwargs(kw)})`")
            lines.append("")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "quality_rules.md").write_text("\n".join(lines), encoding="utf-8")

    with open(ROOT / "docs" / "gx_expectation_mapping.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["rule_id", "layer", "dataset", "severity", "expectation_class", "parameters"])
        for r in ALL_RULES:
            for cls, kw in r.specs:
                w.writerow([r.rule_id, r.layer, kw.get("__dataset__", r.dataset), r.severity, cls, _fmt_kwargs(kw)])

    written = export_suites(ROOT / "gx" / "expectation_suites")
    print(f"docs/quality_rules.md, docs/gx_expectation_mapping.csv and {len(written)} suites written")


if __name__ == "__main__":
    main()
